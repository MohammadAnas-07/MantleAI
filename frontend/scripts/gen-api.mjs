// Generates src/lib/api/schema.ts from the backend's OpenAPI schema.
//
//   npm run gen:api         write openapi.json and schema.ts
//   npm run gen:api:check   fail if the committed files are out of date
//
// The schema comes from backend/scripts/export_openapi.py, which imports the app without
// starting a server or touching a database. Set MANTLE_PYTHON to use another interpreter.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const backend = resolve(here, "../../backend");
const outDir = resolve(here, "../src/lib/api");
const jsonPath = resolve(outDir, "openapi.json");
const tsPath = resolve(outDir, "schema.ts");
const check = process.argv.includes("--check");

function python() {
  if (process.env.MANTLE_PYTHON) return process.env.MANTLE_PYTHON;
  const candidates = [
    resolve(backend, ".venv/Scripts/python.exe"),
    resolve(backend, ".venv/bin/python"),
  ];
  const found = candidates.find((p) => existsSync(p));
  if (!found) {
    console.error("No backend virtualenv found. Create backend/.venv or set MANTLE_PYTHON.");
    process.exit(2);
  }
  return found;
}

const json = execFileSync(python(), [resolve(backend, "scripts/export_openapi.py")], {
  cwd: backend,
  encoding: "utf-8",
  maxBuffer: 64 * 1024 * 1024,
});
const ast = await openapiTS(JSON.parse(json));
const ts =
  "// Generated by `npm run gen:api` from the backend's OpenAPI schema. Do not edit.\n" +
  astToString(ast);

// Git may check files out with CRLF on Windows; compare the text, not the line endings.
const normalize = (text) => text.replace(/\r\n/g, "\n");
const same = (path, text) => existsSync(path) && normalize(readFileSync(path, "utf-8")) === text;

if (check) {
  const stale = [
    [jsonPath, json],
    [tsPath, ts],
  ].filter(([path, text]) => !same(path, normalize(text)));
  if (stale.length > 0) {
    console.error("API types are out of date. Run `npm run gen:api` and commit the result.");
    for (const [path] of stale) console.error(`  stale: ${path}`);
    process.exit(1);
  }
  console.warn("API types are up to date.");
} else {
  writeFileSync(jsonPath, normalize(json));
  writeFileSync(tsPath, normalize(ts));
  console.warn(`Wrote ${jsonPath} and ${tsPath}`);
}
